// Prints the step-type table for docs/map-format.md from the type registry, so the docs can't drift from the code.
// Run: node tools/type-table.js --write   (rewrites the table between the markers, then copies the format doc to the skills' reference)
'use strict';
const fs = require('fs'), path = require('path');
const { load } = require('../test/harness');
const T = load().types;

function table() {
  const rows = T.LIST.map(t => {
    const fields = Object.keys(t.fields).map(f => {
      const d = t.fields[f], name = '`' + f + '`';
      const note = d.options ? ' (' + d.options.map(o => '`' + o + '`').join(', ') + ')' : d.requiredWhen ? ' (for ' + d.requiredWhen.action + ')' : d.requiredUnless ? ' (unless ' + d.requiredUnless.action + ')' : '';
      return (d.required ? '**' + name + '**' : name) + note;
    }).join(', ');
    const rec = (t.record || []).map(d => '`' + d.name + '`' + (d.when ? ' (for ' + d.when.action + ')' : '')).join(', ') || 'nothing (use `evidence:`)';
    return '| `' + t.id + '` | ' + t.hint + ' | ' + fields + ' | ' + rec + ' |';
  });
  return ['| Type | For | Checklist fields (**usual**) | Evidence it can record |', '|---|---|---|---|'].concat(rows).join('\n');
}
const START = '<!-- types:start (generated by tools/type-table.js) -->', END = '<!-- types:end -->';
const SKILL_REF = path.join(__dirname, '..', 'example-folder', '.flightdeck', 'skills', '_flightdeck', 'map-format.md');
function current(doc) { const i = doc.indexOf(START), j = doc.indexOf(END); return i < 0 || j < 0 ? null : doc.slice(i + START.length, j).trim(); }

if (require.main === module) {
  const file = path.join(__dirname, '..', 'docs', 'map-format.md'), doc = fs.readFileSync(file, 'utf8');
  if (process.argv.includes('--write')) {
    const i = doc.indexOf(START), j = doc.indexOf(END);
    if (i < 0 || j < 0) { console.error('Markers not found in docs/map-format.md'); process.exit(1); }
    fs.writeFileSync(file, doc.slice(0, i + START.length) + '\n' + table() + '\n' + doc.slice(j));
    fs.copyFileSync(file, SKILL_REF);
  } else console.log(table());
}
module.exports = { table, current, SKILL_REF };
