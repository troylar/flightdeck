#!/usr/bin/env python3
"""Build dist/flightdeck.html: one self-contained file. Core logic, storage, screens, the example folder, the release
notes and the contract baselines (src/baselines.json) are inlined. Also regenerates CHANGELOG.md from src/releases.json.

    python build.py                                  build dist/flightdeck.html and CHANGELOG.md
    python build.py --check-releases FILE            only validate FILE and print its changelog (used by the tests)
"""
import base64, datetime, json, pathlib, re, sys

root = pathlib.Path(__file__).resolve().parent
CORE = ["core/util.js", "core/types.js", "core/jira.js", "core/map.js", "core/outline.js", "core/timeline.js", "core/publish.js", "core/run.js", "core/corrections.js", "core/skills.js", "core/attach.js", "core/contract.js"]
APP = ["storage/fs.js", "storage/repo.js", "ui/icons.js", "ui/views/common.js", "ui/views/home.js", "ui/views/process.js",
       "ui/views/run.js", "ui/views/pages.js", "ui/views/overlays.js", "ui/views/builder.js", "ui/views/manage.js", "ui/views/flight.js", "ui/examples.js", "ui/app.js"]

# ---- release notes: validate, then embed. A bad entry fails the build rather than shipping a broken page. ----
KINDS = {"new": "New", "improved": "Improved", "fixed": "Fixed"}


def vkey(v):
    return tuple(int(x) for x in v.split("."))


def validate_releases(rel):
    def fail(msg):
        raise ValueError("releases.json: " + msg)
    if not isinstance(rel, list) or not rel:
        fail("must be a non-empty list, newest first")
    seen, prev = set(), None
    for r in rel:
        if not isinstance(r, dict):
            fail("every release must be an object")
        v = r.get("version", "")
        if not isinstance(v, str) or not re.fullmatch(r"\d+\.\d+\.\d+", v):
            fail(f"version {v!r} is not MAJOR.MINOR.PATCH")
        if v in seen:
            fail(f"version {v} appears twice")
        seen.add(v)
        dt = r.get("date", "")
        if not isinstance(dt, str) or not re.fullmatch(r"[0-9]{4}-[0-9]{2}-[0-9]{2}", dt):
            fail(f"{v}: date {dt!r} is not YYYY-MM-DD")
        try:
            d = datetime.date.fromisoformat(dt)
        except ValueError:
            fail(f"{v}: date {dt!r} is not a real date")
        if prev and not vkey(v) < vkey(prev["version"]):
            fail(f"{v} must come after {prev['version']}: list newest first")
        if prev and d > datetime.date.fromisoformat(prev["date"]):
            fail(f"{v} is dated after the newer {prev['version']}")
        if not isinstance(r.get("headline"), str) or not 1 <= len(r["headline"]) <= 140:
            fail(f"{v}: headline must be 1-140 characters")
        extra = set(r) - {"version", "date", "headline", "changes"}
        if extra:
            fail(f"{v}: unknown field(s) {', '.join(sorted(extra))}")
        ch = r.get("changes")
        if not isinstance(ch, list) or not ch:
            fail(f"{v}: needs at least one change")
        for c in ch:
            if not isinstance(c, dict):
                fail(f"{v}: every change must be an object")
            t = c.get("title", "")
            if c.get("kind") not in KINDS:
                fail(f"{v} / {t!r}: kind must be one of {', '.join(KINDS)}")
            for f, lo, hi in (("title", 1, 90), ("area", 1, 30), ("now", 1, 400)):
                if not isinstance(c.get(f), str) or not lo <= len(c[f]) <= hi:
                    fail(f"{v} / {t!r}: {f} must be {lo}-{hi} characters")
            for f, hi in (("before", 400), ("where", 200)):
                if f in c and (not isinstance(c[f], str) or not 1 <= len(c[f]) <= hi):
                    fail(f"{v} / {t!r}: {f}, when given, must be 1-{hi} characters")
            extra = set(c) - {"kind", "area", "title", "before", "now", "where"}
            if extra:
                fail(f"{v} / {t!r}: unknown field(s) {', '.join(sorted(extra))}")
        prev = r


def releases_js(rel):
    """The release list as a JS literal that no text can break out of: every "<" and both JS line separators escaped."""
    return json.dumps(rel, ensure_ascii=False, separators=(",", ":")).replace("<", "\\u003c").replace("\u2028", "\\u2028").replace("\u2029", "\\u2029")


def changelog(rel):
    out = ["# Flightdeck release notes", "", "<!-- Generated by build.py from src/releases.json. Edit that file, not this one. -->", ""]
    for r in rel:
        d = datetime.date.fromisoformat(r["date"])
        out += [f"## {r['version']} · {d.strftime('%b')} {d.day}, {d.year}", "", r["headline"][0].upper() + r["headline"][1:] + ".", ""]
        for k, label in KINDS.items():
            items = [c for c in r["changes"] if c["kind"] == k]
            if not items:
                continue
            out += [f"### {label}", ""]
            for c in items:
                line = f"- **{c['title']}** ({c['area']}). {c['now']}"
                if c.get("where"):
                    line += f" *Where:* {c['where']}"
                out.append(line)
            out.append("")
    return "\n".join(out).rstrip() + "\n"


def load_releases(path):
    rel = json.loads(pathlib.Path(path).read_text(encoding="utf-8"))
    validate_releases(rel)
    return rel


def load_baselines(path):
    """src/baselines.json: every AGENTS.md and skill file Flightdeck has shipped, by content hash. tools/baselines.js writes it."""
    b = json.loads(pathlib.Path(path).read_text(encoding="utf-8"))
    if not isinstance(b, dict) or b.get("format") != "flightdeck-baselines/1" or not isinstance(b.get("files"), dict):
        raise ValueError("baselines.json: format must be flightdeck-baselines/1 with a files object")
    for f, hashes in b["files"].items():
        if not isinstance(hashes, dict) or not all(re.fullmatch(r"[0-9a-f]{64}", h) and isinstance(v, list) and v and all(isinstance(x, str) and re.fullmatch(r"\d+\.\d+\.\d+", x) for x in v) for h, v in hashes.items()):
            raise ValueError(f"baselines.json: {f} must map sha-256 hashes to lists of versions")
    return b


def read(rel_path):
    return (root / "src" / rel_path).read_text(encoding="utf-8")


def main():
    try:
        releases = load_releases(root / "src" / "releases.json")
    except (ValueError, json.JSONDecodeError) as e:
        sys.exit(str(e))
    version = releases[0]["version"]
    try:
        baselines = load_baselines(root / "src" / "baselines.json")
    except (ValueError, json.JSONDecodeError) as e:
        sys.exit(str(e))

    examples = {}
    ex = root / "example-folder"
    for p in sorted(ex.rglob("*")):
        if p.is_file() and (p.suffix in (".md", ".json") or (p.suffix == ".py" and ".flightdeck" in p.parts)) and (p.name != "AGENTS.md" or p.parent == ex):
            examples[p.relative_to(ex).as_posix()] = p.read_text(encoding="utf-8")


    def script_safe(s):
        return s.replace("</script", "<\\/script")


    page = read("page.html")
    core = "\n".join(read(f) for f in CORE)
    if core.count("/*@BASELINES@*/{}") != 1:
        sys.exit("core/contract.js must contain the /*@BASELINES@*/{} placeholder exactly once")
    # One line, so the command line can read it back out of the page.
    core = core.replace("/*@BASELINES@*/{}", releases_js(baselines))
    app = "\n".join(read(f) for f in APP)
    blob = json.dumps(examples, ensure_ascii=False).replace("</", "<\\/")
    for marker in ("/*@EXAMPLES@*/{}", "/*@RELEASES@*/[]"):
        if app.count(marker) != 1:
            sys.exit(f"ui/app.js must contain the {marker} placeholder exactly once")
    app = app.replace("/*@EXAMPLES@*/{}", blob).replace("/*@RELEASES@*/[]", releases_js(releases))
    fonts = "".join(
        "@font-face{font-family:'Barlow Condensed';font-style:normal;font-weight:%s;font-display:swap;"
        "src:url(data:font/woff2;base64,%s) format('woff2');}" % (w, base64.b64encode((root / "src" / "fonts" / ("barlow-condensed-%s.woff2" % w)).read_bytes()).decode("ascii"))
        for w in (600, 700))
    if "/*@FONTS@*/" not in page:
        sys.exit("page.html is missing the /*@FONTS@*/ placeholder")
    # The embedded fonts travel with their license (SIL OFL 1.1 requires the notice and license with every copy).
    ofl = (root / "src" / "fonts" / "OFL.txt").read_text(encoding="utf-8")
    if "*/" in ofl:
        sys.exit("src/fonts/OFL.txt can't be embedded in a CSS comment")
    fonts = "/* Barlow Condensed, embedded below.\n" + ofl + "\n*/" + fonts
    (root / "dist").mkdir(exist_ok=True)
    (root / "dist" / "FONT-LICENSE.txt").write_text(ofl, encoding="utf-8")
    page = page.replace("/*@FONTS@*/", fonts)
    # The version stamp near the top of the page: another copy of Flightdeck reads it to tell whether a newer copy exists.
    VERSION_META = '<meta name="flightdeck-version" content="dev">'
    if page.count(VERSION_META) != 1:
        sys.exit("page.html must contain the version meta placeholder exactly once")
    # Copies from before the rename look for preflight-version; both stamps let them see an update.
    page = page.replace(VERSION_META, f'<meta name="flightdeck-version" content="{version}"><meta name="preflight-version" content="{version}">')
    out = page.replace("/*@CORE@*/", script_safe(core)).replace("/*@APP@*/", script_safe(app))
    for marker in ("/*@CORE@*/", "/*@APP@*/", "/*@EXAMPLES@*/", "/*@FONTS@*/", "/*@RELEASES@*/", "/*@BASELINES@*/"):
        if marker in out:
            sys.exit(f"unreplaced placeholder {marker}")
    (root / "dist").mkdir(exist_ok=True)
    (root / "dist" / "flightdeck.html").write_text(out, encoding="utf-8")
    (root / "CHANGELOG.md").write_text(changelog(releases), encoding="utf-8")
    # The npm package carries the same version as the app and the changelog.
    pkg_path = root / "package.json"
    if pkg_path.exists():
        pkg = json.loads(pkg_path.read_text(encoding="utf-8"))
        if pkg.get("version") != version:
            pkg["version"] = version
            pkg_path.write_text(json.dumps(pkg, indent=2) + "\n", encoding="utf-8")
    print(f"built dist/flightdeck.html {version} ({len(out.encode()) // 1024} KB, {len(examples)} example files, {len(releases)} releases)")


if __name__ == "__main__":
    if len(sys.argv) == 3 and sys.argv[1] == "--check-releases":
        try:
            sys.stdout.write(changelog(load_releases(sys.argv[2])))
        except (ValueError, json.JSONDecodeError) as e:
            sys.exit(str(e))
    else:
        main()
